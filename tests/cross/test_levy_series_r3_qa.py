@pytest.mark.parametrize("plate", list(HP))
@pytest.mark.parametrize("M", [1, 9, 1131])
def test_field_139_against_high_precision(plate, M):
    """(139) at centre, interior and near all four edges (1e-6, 1e-9 of a side), original coordinates."""
    a, b = plate
    x = np.array([fx * a for fx, _ in PTS])
    y = np.array([fy * b for _, fy in PTS])
    got = lv.levy_series_w(x, y, a=a, b=b, q=1.0, D=1.0, M=M)
    model = lv.levy_field_bounds(a=a, b=b, q=1.0, D=1.0, M=M).rounding_model
    for g, ref in zip(got, HP[plate][M]):
        assert abs(g - float(ref)) <= model, (g, ref)


@pytest.mark.parametrize("plate", list(HP))
def test_first_term_is_v29_along_the_shorter_side(plate):
    """M = 1 equals В-29 with X0 along a_L = min(a, b) (for b < a - the start along y); QA's double closed form."""
    a, b = plate
    aL, bL = min(a, b), max(a, b)
    al = math.pi * bL / (2 * aL)
    P, R, C0 = (al * math.tanh(al) + 2) / (2 * math.cosh(al)), 1 / (2 * math.cosh(al)), 4 * aL**4 / math.pi**5
    for fx, fy in ((0.5, 0.5), (0.2, 0.7), (0.9, 0.15)):
        x, y = fx * a, fy * b
        xL, eta = (y, x - a / 2) if b < a else (x, y - b / 2)
        t = math.pi * eta / aL
        ref = C0 * (1 - P * math.cosh(t) + R * t * math.sinh(t)) * math.sin(math.pi * xL / aL)
        got = float(lv.levy_series_w(x, y, a=a, b=b, q=1.0, D=1.0, M=1))
        assert abs(got - ref) <= 64 * U * C0


def test_square_first_term_equals_r2_levy_w1():
    xs = np.linspace(0.0, 1.3, 41)
    got = lv.levy_series_w_grid(xs, xs, a=1.3, b=1.3, q=-2.0, D=0.7, M=1)
    ref = lv.levy_w1(xs[:, None], xs[None, :], a=1.3, q=-2.0, D=0.7)
    assert np.max(np.abs(got - ref)) <= 64 * U * 4 * 2.0 * 1.3**4 / (math.pi**5 * 0.7)


@pytest.mark.parametrize("r_L", list(ALPHA))
def test_centre_140_and_j(r_L):
    """alpha of (141) by (140) against high precision within truncation + model; (j) at M = 1131 agrees within ЧВ-Л4."""
    ref = float(ALPHA[r_L])
    got = lv.levy_alpha_141(r_L)
    b140 = lv.levy_centre_bounds(a=1.0, b=r_L, q=1.0, D=1.0)
    assert abs(got - ref) <= b140.truncation + b140.rounding_model
    bj = lv.levy_centre_bounds(a=1.0, b=r_L, q=1.0, D=1.0, form="j")
    assert abs(lv.levy_centre_j(a=1.0, b=r_L, q=1.0, D=1.0) - ref) <= bj.truncation + bj.rounding_model
    # turned plate in the original normalisation: w_bar(1/r) = r^-4 alpha(r)
    assert abs(lv.levy_centre_wbar(1.0 / r_L) - ref / r_L**4) <= (b140.truncation + b140.rounding_model) / r_L**4 + 4 * U * ref / r_L**4


@pytest.mark.parametrize("r_L", [1.0, 2.0, 5.0])
def test_truncation_bound_on_control_data(r_L):
    """|w_M - w_20001| <= B_L(M) + B_L(20001) + models, also at x = 0.4 a / M where the tail is largest (not a proof)."""
    for plate in ((1.0, r_L), (r_L, 1.0)):
        a, b = plate
        for M in (1, 3, 9, 39, 159):
            x = np.array([0.4 * a / M, 0.5 * a, 1e-6 * a]) if b >= a else np.array([0.5 * a, 0.2 * a, 0.7 * a])
            y = np.array([0.5 * b, 0.3 * b, 0.4 * b]) if b >= a else np.array([0.4 * b / M, 0.5 * b, 1e-6 * b])
            wm = lv.levy_series_w(x, y, a=a, b=b, q=1.0, D=1.0, M=M)
            wr = lv.levy_series_w(x, y, a=a, b=b, q=1.0, D=1.0, M=20001)
            bm, br = lv.levy_field_bounds(a=a, b=b, q=1.0, D=1.0, M=M), lv.levy_field_bounds(a=a, b=b, q=1.0, D=1.0, M=20001)
            assert np.all(np.abs(wm - wr) <= bm.truncation + br.truncation + bm.rounding_model + br.rounding_model)


def test_large_alpha_without_overflow():
    """r_L = 5: alpha_m up to 1.6e5 (M = 20001); overflow, invalid and divide are errors, underflow to 0 is exact."""
    with np.errstate(over="raise", invalid="raise", divide="raise", under="ignore"):
        for a, b in ((1.0, 5.0), (5.0, 1.0)):
            for M in (1131, 20001):
                w = lv.levy_series_w_grid(np.linspace(0, a, 9), np.linspace(0, b, 9), a=a, b=b, q=1.0, D=1.0, M=M)
                assert np.all(np.isfinite(w)) and np.all(w[1:-1, 1:-1] > 0)


@pytest.mark.parametrize(("a", "b"), [(1.0, 2.0), (3.0, 1.0), (1.0, 5.0)])
def test_reflections_and_edges(a, b):
    """Exact zeros on the four edges; reflections x -> a - x, y -> b - y within the rounding model."""
    xs, ys = np.linspace(0, a, 13), np.linspace(0, b, 17)
    w = lv.levy_series_w_grid(xs, ys, a=a, b=b, q=1.0, D=1.0, M=159)
    assert np.all(w[[0, -1], :] == 0.0) and np.all(w[:, [0, -1]] == 0.0)
    model = lv.levy_field_bounds(a=a, b=b, q=1.0, D=1.0, M=159).rounding_model
    assert np.max(np.abs(w - w[::-1, :])) <= 2 * model and np.max(np.abs(w - w[:, ::-1])) <= 2 * model
